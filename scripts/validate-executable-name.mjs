import fs from 'node:fs';
import { compileMangaName } from '../core/manga-grammar.mjs';
import { renderExecutableNameSvg } from '../core/blueprint-renderer.mjs';
const src=fs.readFileSync('examples/combat-1p.md','utf8');
const p=compileMangaName(src,{title:'combat-1p'});
const page=p.pages[0];
if(!page.layoutDecision?.winner) throw new Error('missing layout decision');
if(!Array.isArray(page.layoutDecision.candidates)||page.layoutDecision.candidates.length<3) throw new Error('missing layout candidates');
if(!page.panels.every(x=>x.importance&&typeof x.importance.energy==='number')) throw new Error('missing energy');
if(!page.panels.some(x=>x.shape?.preset?.startsWith('diagonal'))) throw new Error('missing diagonal geometry');
if(!page.panels.some(x=>x.inset?.kind==='panel-in-panel')) throw new Error('missing inset');
if(!page.panels.some(x=>x.interactions?.some(y=>y.type==='contact'))) throw new Error('missing contact');
const clean=renderExecutableNameSvg(p,0,{annotated:false});
const annotated=renderExecutableNameSvg(p,0,{annotated:true});
if(clean.includes('PRIMARY:')||clean.includes('CONTACT:')||clean.includes('fill="#2563eb"')) throw new Error('clean contains annotation layer');
if(!annotated.includes('id="annotations"')||!annotated.includes('CONTACT:')) throw new Error('annotated review missing semantics');
if(!clean.includes('id="art"')) throw new Error('clean missing art layer');
const p2=compileMangaName(src,{title:'combat-1p'});
if(JSON.stringify(p)!==JSON.stringify(p2)) throw new Error('compiler not deterministic');
console.log('Executable Name validation passed:',page.layoutDecision.winner,page.layoutDecision.score.toFixed(3));
